CREATE TABLE nations_dump (
    dbid BIGINT PRIMARY KEY,
    name TEXT NOT NULL,
    canon_name TEXT NOT NULL UNIQUE,
    classification TEXT,
    fullname TEXT,
    motto TEXT,
    category TEXT,
    unstatus TEXT,
    is_wa BOOLEAN,
    is_delegate BOOLEAN,
    endorsements TEXT[],
    issues_answered BIGINT,
    freedoms JSONB,
    region TEXT,
    population BIGINT,
    tax DOUBLE PRECISION,
    animal TEXT,
    currency TEXT,
    demonym TEXT,
    demonym2 TEXT,
    demonym2plural TEXT,
    flag_url TEXT,
    major_industry TEXT,
    govt_priority TEXT,
    government JSONB,
    founded TEXT,
    firstlogin BIGINT,
    lastlogin BIGINT,
    lastactivity TEXT,
    influence TEXT,
    influencenum DOUBLE PRECISION,
    freedom_scores JSONB,
    public_sector DOUBLE PRECISION,
    deaths JSONB,
    leader TEXT,
    capital TEXT,
    religion TEXT,
    factbooks BIGINT,
    dispatches BIGINT
);

CREATE UNIQUE INDEX idx_nation_canon_name ON nations_dump(canon_name);